export function formatCompactVnd(amount: number): string {
  if (amount >= 1_000_000_000) {
    return (amount / 1_000_000_000).toFixed(2).replace('.', ',') + ' tỷ ₫';
  }
  if (amount >= 1_000_000) {
    return (amount / 1_000_000).toFixed(1).replace('.', ',') + ' tr ₫';
  }
  return formatVnd(amount);
}

export function formatNumber(num: number): string {
  return new Intl.NumberFormat('vi-VN').format(num);
}

export function calculateGrowth(
  current: number,
  previous: number,
  isCurrency = false,
): {
  diffPercent: number;
  isUp: boolean;
  formattedPercent: string;
  formattedPrevious: string;
  isNeutral: boolean;
} {
  if (previous === 0) {
    return {
      diffPercent: 0,
      isUp: true,
      formattedPercent: '0%',
      formattedPrevious: isCurrency ? formatCompactVnd(previous) : formatNumber(previous),
      isNeutral: true,
    };
  }

  const diff = ((current - previous) / previous) * 100;
  const isUp = diff >= 0;
  const formattedPercent = (isUp ? '+' : '-') + Math.abs(diff).toFixed(1).replace('.', ',') + '%';
  const formattedPrevious = isCurrency ? formatCompactVnd(previous) : formatNumber(previous);

  return {
    diffPercent: diff,
    isUp,
    formattedPercent,
    formattedPrevious,
    isNeutral: false,
  };
}

